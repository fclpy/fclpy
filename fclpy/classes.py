def register_method_combination_type(type_: MethodCombinationType) -> MethodCombinationType:
    """Install a method combination type under its name. DEFINE-METHOD-
    COMBINATION redefining an existing name replaces it here, which is what
    makes every generic function already using it pick the new definition
    up (they hold the *object*, which holds the type by reference)."""
    _method_combination_types[type_.name_string.upper()] = type_
    return type_


def find_method_combination_type(name) -> Optional[MethodCombinationType]:
    key = (name.name if isinstance(name, LispSymbol) else str(name)).upper()
    return _method_combination_types.get(key)


STANDARD_METHOD_COMBINATION = StandardMethodCombination(_cl_symbol('STANDARD'))
register_method_combination_type(STANDARD_METHOD_COMBINATION)

# CLHS 7.6.6.4's built-in combination types, each defined as if by the short
# form of DEFINE-METHOD-COMBINATION with itself as the operator. APPEND and
# LIST are the two that are *not* :identity-with-one-argument, which is
# observable: with a single applicable method, the LIST combination answers
# `(x)` and not `x`.
for _op, _identity in (('PROGN', True), ('AND', True), ('OR', True), ('+', True),
                       ('MAX', True), ('MIN', True), ('NCONC', True),
                       ('APPEND', False), ('LIST', False)):
    register_method_combination_type(
        ShortFormMethodCombination(_cl_symbol(_op), identity_with_one_argument=_identity))
del _op, _identity


def method_combination_of(gf: GenericFunction) -> MethodCombination:
    """The method combination in force for `gf` -- standard unless
    DEFGENERIC said otherwise."""
    comb = getattr(gf, 'method_combination', None)
    if comb is None:
        return MethodCombination(STANDARD_METHOD_COMBINATION)
    return comb


def call_generic_function(gf: GenericFunction, args: List[Any]) -> Any:
    """Call a generic function: compute the applicable methods, then let the
    generic function's method combination assemble and run them (CLHS
    7.6.6)."""
    if not gf.methods:
        installer = _default_method_installers.get(_gf_name(gf))
        if installer is not None:
            installer(gf)

    applicable = compute_applicable_methods(gf, args)
    if not applicable:
        # CLHS 7.6.6: no applicable methods is decided *before* the method
        # combination is consulted, and is an error for every combination --
        # not something a combination can answer by combining nothing. A
        # long-form combination whose body maps over an empty method group
        # otherwise happily produces `(vector)` and returns #().
        _no_applicable_method(gf, args)
    return method_combination_of(gf).invoke(gf, applicable, args)


_UNSET_KEYWORD_CONTEXT = object()


def _compute_frame_keyword_context(frame: Dict[str, Any]) -> Optional[Any]:
    """The CLHS 7.6.5 keyword-argument validity in force for one method
    invocation: the union of the keyword parameters named by the generic
    function's lambda list and by the lambda list of every *applicable*
    method, plus whether &allow-other-keys applies anywhere (in the generic
    function's own lambda list or in any applicable method's -- either one
    makes every keyword acceptable).

    Computed once per invocation and memoized on the frame. None means
    nothing is known (no generic function, or no Lisp lambda lists) and the
    caller's own lambda list decides alone.
    """
    gf = frame.get('gf')
    if not isinstance(gf, GenericFunction):
        return None
    from fclpy.lispfunc.evaluation_special_forms import (_keyword_param_parts,
                                                         keyword_argument_key)
    from fclpy.lispfunc.evaluation_core import parse_lambda_list

    valid: set = set()
    allow_all = False

    def absorb(lambda_list: Any) -> None:
        nonlocal allow_all
        if lambda_list is None:
            return
        try:
            tail = parse_lambda_list(lambda_list)
        except Exception:
            return
        if tail.get('allow_other_keys'):
            allow_all = True
        for spec in tail.get('keyword', []):
            try:
                keyword, _var, _default, _supplied = _keyword_param_parts(spec)
                valid.add(keyword_argument_key(keyword))
            except Exception:
                continue

    absorb(gf.lambda_list)
    try:
        applicable = compute_applicable_methods(gf, list(frame.get('args') or []))
    except Exception:
        applicable = []
    for method in applicable:
        if method is frame.get('method'):
            # The executing method's own lambda list is what the caller is
            # already checking against.
            continue
        absorb(getattr(method, 'lambda_list', None))
    return (valid, allow_all)


def call_frame_keyword_context() -> Optional[Any]:
    """The keyword-argument validity for the method currently executing on
    this thread, or None outside any method invocation. See
    `_compute_frame_keyword_context`."""
    if not _call_stack:
        return None
    frame = _call_stack[-1]
    ctx = frame.get('kw_ctx', _UNSET_KEYWORD_CONTEXT)
    if ctx is _UNSET_KEYWORD_CONTEXT:
        ctx = _compute_frame_keyword_context(frame)
        frame['kw_ctx'] = ctx
    return ctx


def current_call_frame() -> Optional[Dict[str, Any]]:
    """The frame of the method currently executing on this thread, or None
    outside any method invocation -- the thing `#'call-next-method` and
    `#'next-method-p` close over for their indefinite extent."""
    return _call_stack[-1] if _call_stack else None


def call_next_method(*args) -> Any:
    """CALL-NEXT-METHOD: call the next method in the chain the currently
    executing method was given by CALL-METHOD."""
    if not _call_stack:
        raise LispProgramError(
            "CALL-NEXT-METHOD: no method is currently executing")
    return call_next_method_in_frame(_call_stack[-1], *args)


def call_next_method_in_frame(frame: Dict[str, Any], *args) -> Any:
    """CALL-NEXT-METHOD against one captured frame -- the core the bare
    operator and the frame-capturing closures a method's environment binds
    both share, so a funcalled `#'call-next-method` after its method
    returned walks the chain it captured, not whatever is running now."""
    call_args = list(args) if args else frame['args']
    remaining = frame['next']
    if args:
        _check_cnm_argument_order(frame, call_args)
    if not remaining:
        raise LispProgramError(
            f"CALL-NEXT-METHOD: no next method for {_gf_name(frame['gf'])}")
    return call_method(remaining[0], remaining[1:], call_args)


def _check_cnm_argument_order(frame: Dict[str, Any], new_args: List[Any]) -> None:
    """CLHS call-next-method's argument rule: "the ordered set of applicable
    methods for a changed set of arguments for call-next-method must be the
    same as the ordered set of applicable methods for the original arguments
    to the generic function" -- otherwise an error is signaled. The eql-0
    method calling `(call-next-method 1)` changed which methods apply
    (its own specializer no longer matches), which is exactly the
    inconsistency the rule exists to catch."""
    gf = frame.get('gf')
    if not isinstance(gf, GenericFunction):
        return
    try:
        original = compute_applicable_methods(gf, list(frame['args']))
        changed = compute_applicable_methods(gf, list(new_args))
    except Exception:
        return
    if [id(m) for m in original] != [id(m) for m in changed]:
        raise LispProgramError(
            "CALL-NEXT-METHOD: the changed arguments do not select the same "
            f"ordered set of applicable methods for {_gf_name(gf)}")


def next_method_p() -> bool:
    """NEXT-METHOD-P: would CALL-NEXT-METHOD succeed right now?"""
    if not _call_stack:
        return False
    return bool(_call_stack[-1]['next'])


def effective_method_arguments() -> List[Any]:
    """The arguments of the generic-function call whose effective method
    form is being evaluated -- CALL-METHOD's implicit operands."""
    if not _effective_context:
        raise LispProgramError(
            "CALL-METHOD is only valid inside an effective method form")
    return _effective_context[-1]['args']


def make_method_from_thunk(run: Callable, generic_function=None) -> MakeMethod:
    """Wrap `run(*args)` as the method `(MAKE-METHOD form)` denotes, with the
    effective-method context established around it so a CALL-METHOD nested
    inside that form still knows the original call's arguments."""
    def invoke(*call_args):
        _effective_context.append(
            {'gf': generic_function, 'args': list(call_args), 'env': None})
        try:
            return run(*call_args)
        finally:
            _effective_context.pop()

    return MakeMethod(invoke, generic_function)


