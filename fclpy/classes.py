def _init_builtin_classes():
    """Register the standardized classes of CLHS 4.2 with the superclass
    edges their dictionary entries give them."""
    global _builtin_classes_initialized
    if _builtin_classes_initialized:
        return
    _builtin_classes_initialized = True

    from fclpy.lisptype import COMMON_LISP_PACKAGE

    classes = {}
    for type_name, (_supers, _metaclass) in _BUILTIN_CLASS_TABLE.items():
        sym = COMMON_LISP_PACKAGE.intern_symbol(type_name)
        classes[type_name] = LispClass(name=sym, direct_superclasses=[],
                                       direct_slots=[],
                                       metaclass_name=_metaclass)
    # Wire the superclass edges in a second pass, now that every object
    # exists (the table is not topologically ordered).
    for type_name, (supers, _metaclass) in _BUILTIN_CLASS_TABLE.items():
        classes[type_name].direct_superclasses = [classes[s] for s in supers]
    for cls in classes.values():
        register_class(cls)


# Initialize built-in classes when module is loaded
_init_builtin_classes()
